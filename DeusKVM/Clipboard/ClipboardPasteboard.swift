import AppKit
import Carbon

/// All potentially blocking pasteboard reads stay off the input/main run loops.
final class ClipboardPasteboard: @unchecked Sendable {
    struct Snapshot: Sendable {
        let epoch: UInt32
        let generation: UInt64
        let revision: Int
        let text: Data?
        let file: ClipboardFile?
        let network: FileNetworkOffer?
    }

    static let ownType = NSPasteboard.PasteboardType("io.github.amadeus.deuskvm.clipboard")
    static let excludedTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
        "com.agilebits.onepassword", "public.file-url", ownType.rawValue
    ]
    private let gate = NSLock()
    private var permittedGeneration: UInt64 = 0
    private var generation: UInt64 = 0
    private var permitted = false
    private let queue = DispatchQueue(label: "DeusKVM.clipboard")
    private let board: NSPasteboard
    private var retry: DispatchWorkItem?
    private var requestDeadline: TimeInterval = 0
    private var epoch: UInt32 = 0
    private var enabled = false
    private var versions = ClipboardRevision()
    private var priming = true
    private var pendingYield = false
    private struct Pending {
        let text: Data?
        let file: ClipboardFileOffer?
        var image: Data?
        let revision: Int
        let deadline: TimeInterval
    }

    private var pending: Pending?
    private var file: ClipboardFile?
    private var imageReceiver: FileNetworkReceiver?
    private var imageLease: ClipboardImageLease?
    private lazy var network = FileNetworkServer(queue: queue) { [weak self] epoch, sequence, offset, count in
        self?.fileBytes(epoch: epoch, sequence: sequence, offset: offset, count: count)
    }

    var remoteFile: (@Sendable (ClipboardFileOffer, Int, UInt64) -> Void)?
    var requestImage: (@Sendable (ClipboardFileOffer, UInt64) -> Void)?
    var importedImage: (@Sendable (Int, UInt64) -> Void)?
    private let snapshot: @Sendable (Snapshot) -> Void
    private let yielded: @Sendable (UInt32, UInt64) -> Void

    init(
        board: NSPasteboard = .general,
        snapshot: @escaping @Sendable (Snapshot) -> Void,
        yielded: @escaping @Sendable (UInt32, UInt64) -> Void
    ) {
        self.board = board; self.snapshot = snapshot; self.yielded = yielded
    }

    @discardableResult
    func configure(epoch: UInt32, enabled: Bool) -> UInt64 {
        let next = gate.withLock {
            permittedGeneration &+= 1; permitted = enabled
            return permittedGeneration
        }
        queue.async { [self] in
            generation = next
            clearImage()
            self.epoch = epoch; self.enabled = enabled
            versions = ClipboardRevision(); pending = nil; file = nil; priming = true; pendingYield = false
            network.configure(enabled)
            retry?.cancel(); retry = nil
            if enabled { requestPoll() }
        }
        return next
    }

    func yield() {
        queue.async { [self] in pendingYield = true; requestPoll() }
    }

    func write(_ text: Data, epoch: UInt32, revision: Int) {
        queue.async { [self] in
            guard enabled, self.epoch == epoch else { return }
            clearImage()
            pending = Pending(text: text, file: nil, revision: revision, deadline: ProcessInfo.processInfo.systemUptime + 2)
            requestPoll()
        }
    }

    func writeFile(_ offer: ClipboardFileOffer, revision: Int) {
        queue.async { [self] in
            guard enabled, epoch == offer.epoch, offer.valid else { return }
            clearImage()
            pending = Pending(text: nil, file: offer, revision: revision, deadline: ProcessInfo.processInfo.systemUptime + 2)
            requestPoll()
        }
    }

    private func fileBytes(epoch: UInt32, sequence: UInt32, offset: UInt32, count: Int) -> Data? {
        guard enabled, canAccess, !IsSecureEventInputEnabled(), self.epoch == epoch,
              UInt32(truncatingIfNeeded: board.changeCount) == sequence,
              let file else { return nil }
        let bytes = file.read(offset: offset, count: count)
        guard canAccess, !IsSecureEventInputEnabled(),
              UInt32(truncatingIfNeeded: board.changeCount) == sequence else { return nil }
        return bytes
    }

    private var canAccess: Bool {
        gate.withLock { permitted && permittedGeneration == generation }
    }

    func cancelImage() {
        queue.async { [self] in clearImage() }
    }

    private func clearImage() {
        imageLease?.cancel(); imageReceiver?.cancel()
        imageLease = nil; imageReceiver = nil
    }

    private func receiveImage(_ offer: ClipboardFileOffer, revision: Int, localRevision: Int) {
        let token = ClipboardImageLease(), expected = generation
        imageLease = token
        let receiver = FileNetworkReceiver(offer: offer, destination: nil, canAccess: { [weak self] in
            guard let self else { return false }
            return token.valid && gate.withLock { permitted && permittedGeneration == expected } &&
                !IsSecureEventInputEnabled() && board.changeCount == revision
        }, ready: { [weak self] request in
            guard token.valid else { return }
            self?.requestImage?(request, expected)
        }, progress: { _ in }, completion: { [weak self] _ in
            self?.queue.async { [weak self] in
                guard let self, imageLease === token else { return }
                imageReceiver = nil; imageLease = nil
            }
        }, received: { [weak self] bytes in
            self?.queue.async { [weak self] in
                guard let self, token.valid, canAccess, generation == expected, board.changeCount == revision else { return }
                pending = Pending(
                    text: nil, file: nil, image: bytes, revision: localRevision,
                    deadline: ProcessInfo.processInfo.systemUptime + 2
                )
                requestPoll()
            }
        })
        imageReceiver = receiver; receiver.start()
    }

    /// Only initialization, handoff and incoming writes request a read. Retries are
    /// bounded to this operation (pasteboard contention or a starting network listener).
    private func requestPoll() {
        requestDeadline = ProcessInfo.processInfo.systemUptime + 2
        poll()
    }

    private func retryIfNeeded() {
        guard enabled, canAccess, priming || pendingYield || pending != nil,
              ProcessInfo.processInfo.systemUptime < requestDeadline else { return }
        let expected = generation
        let work = DispatchWorkItem { [weak self] in
            guard let self, generation == expected, canAccess else { return }
            poll()
        }
        retry = work
        queue.asyncAfter(deadline: .now() + 0.05, execute: work)
    }

    private func poll() {
        retry?.cancel(); retry = nil
        guard enabled, canAccess else { return }
        defer { retryIfNeeded() }
        let revision = board.changeCount
        if versions.observed != revision {
            guard !IsSecureEventInputEnabled() else { return }
            clearImage()
            pending = nil
            let types = Set((board.types ?? []).map(\.rawValue))
            var bytes: Data?
            file = nil
            let privateTypes = Self.excludedTypes.subtracting(["public.file-url"])
            if types.contains("public.file-url"), types.isDisjoint(with: privateTypes),
               let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
               urls.count == 1 { file = ClipboardFile(urls[0]) }
            if types.isDisjoint(with: Self.excludedTypes), let png = ClipboardImage.capture(board) {
                file = ClipboardFile(png: png)
            }
            if file == nil, types.isDisjoint(with: Self.excludedTypes),
               let data = board.data(forType: .string), data.count <= ClipboardTransfer.maximumBytes * 2
            {
                bytes = ClipboardTransfer.text(String(data: data, encoding: .utf8))
            }
            guard canAccess, board.changeCount == revision else { return }
            if file != nil, network.starting { return }
            versions.capture(revision)
            let endpoint = network.offer(epoch: epoch, sequence: UInt32(truncatingIfNeeded: revision), file: file != nil)
            snapshot(Snapshot(
                epoch: epoch,
                generation: generation,
                revision: revision,
                text: bytes,
                file: file,
                network: endpoint
            ))
            priming = false
        }
        if pendingYield { pendingYield = false; yielded(epoch, generation) }
        if let update = pending { apply(update, revision: revision) }
    }

    private func apply(_ update: Pending, revision: Int) {
        guard !IsSecureEventInputEnabled() else { return }
        guard versions.canApply(expectedLocal: update.revision, current: revision),
              ProcessInfo.processInfo.systemUptime <= update.deadline else { pending = nil; return }
        if let offer = update.file, offer.isImage {
            pending = nil
            receiveImage(offer, revision: revision, localRevision: update.revision)
            return
        }
        let item: NSPasteboardItem
        if let png = update.image {
            guard let image = ClipboardImage.item(png) else { pending = nil; return }
            item = image
        } else {
            item = NSPasteboardItem()
        }
        if let offer = update.file {
            guard let metadata = try? JSONEncoder().encode(offer) else { pending = nil; return }
            item.setData(metadata, forType: NSPasteboard.PasteboardType("io.github.amadeus.deuskvm.remote-file"))
        } else if update.image == nil {
            guard let bytes = update.text, let text = ClipboardTransfer.decode(bytes) else { pending = nil; return }
            item.setString(text, forType: .string)
        }
        item.setData(Data(), forType: Self.ownType)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        guard canAccess, board.changeCount == revision else { pending = nil; return }
        board.clearContents()
        if board.writeObjects([item]) {
            versions.imported(board.changeCount); pending = nil; file = nil; network.revoke()
            if let offer = update.file { remoteFile?(offer, board.changeCount, generation) }
            if update.image != nil { importedImage?(board.changeCount, generation) }
        }
    }

    deinit { retry?.cancel() }
}
